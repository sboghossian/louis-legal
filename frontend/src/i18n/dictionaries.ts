/**
 * Translation dictionaries.
 *
 * Each language is keyed by the same set of canonical English strings.
 * English IS the source of truth — missing keys in other languages fall
 * back to the English value, so adding new UI copy doesn't crash a
 * non-English user.
 *
 * Translation philosophy:
 * - Translate UI chrome (nav, button labels, settings labels). Don't
 *   translate proprietary product names ("Louis", "Drafting Board",
 *   "Tabular Review") — they read as nouns.
 * - Don't try to translate model output, document text, or skill bodies
 *   from the dictionary. That's the assistant's job at runtime.
 * - Technical terms ("MCP", "API key", "AES-256", "BYO", "MIT licensed")
 *   stay in English across every locale.
 *
 * Pluralization:
 * - The translator uses simple `{count}` interpolation. Languages with
 *   complex plural rules (Russian, Arabic, Polish) get the grammatically
 *   safest "many / N" form — see for example `prompts.showing`. If you
 *   need full ICU MessageFormat, branch the call site, not this file.
 *
 * See docs/I18N.md for the translator pattern, RTL handling, and the
 * list of keys still waiting on `t(...)` wiring in source code.
 */

